"""Safe SQL identifiers for dataset schemas, tables, columns and roles.

PostgreSQL can't take identifiers (schema/table/column names) as bind parameters,
so DDL and preview queries must embed them in the SQL text. To keep that safe:

1. identifiers are either generated by the server (``ds_<hex>``) or normalised to a
   strict pattern (lowercase ASCII, digits, underscore, max 63 bytes); and
2. ``quote_ident`` refuses anything that doesn't match, then double-quotes it.

Values (limits, filters, text) are always passed as bind parameters, never inlined.
"""

from __future__ import annotations

import re
import uuid

SAFE_IDENTIFIER = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
DATASET_SCHEMA = re.compile(r"^ds_[0-9a-f]{32}$")
READER_ROLE = re.compile(r"^ds_[0-9a-f]{32}_r$")


class UnsafeIdentifierError(ValueError):
    pass


def quote_ident(name: str) -> str:
    if not SAFE_IDENTIFIER.fullmatch(name):
        raise UnsafeIdentifierError(f"Refusing unsafe SQL identifier: {name!r}")
    return f'"{name}"'


def qualified(schema: str, table: str) -> str:
    return f"{quote_ident(schema)}.{quote_ident(table)}"


def new_dataset_identifiers() -> tuple[str, str]:
    """Fresh (schema_name, reader_role) for a dataset."""
    hex_id = uuid.uuid4().hex
    return f"ds_{hex_id}", f"ds_{hex_id}_r"


def assert_dataset_schema(schema: str) -> str:
    if not DATASET_SCHEMA.fullmatch(schema):
        raise UnsafeIdentifierError(f"Not a dataset schema: {schema!r}")
    return schema


def assert_reader_role(role: str) -> str:
    if not READER_ROLE.fullmatch(role):
        raise UnsafeIdentifierError(f"Not a dataset reader role: {role!r}")
    return role
