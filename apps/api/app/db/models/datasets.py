"""Dataset catalog: datasets, their tables, columns, relationships and ingestion jobs."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, CreatedAtMixin, TimestampMixin, uuid7

DATASET_STATUSES = ("pending_review", "loading", "ready", "failed", "deleting")
COLUMN_TYPES = ("integer", "bigint", "numeric", "boolean", "date", "timestamptz", "text")
SEMANTIC_ROLES = ("identifier", "measure", "dimension", "time", "currency")


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class Dataset(TimestampMixin, Base):
    __tablename__ = "datasets"
    __table_args__ = (
        UniqueConstraint("owner_id", "name"),
        CheckConstraint("source_type IN ('demo', 'upload_csv')", name="source_type"),
        CheckConstraint(_in("status", DATASET_STATUSES), name="status"),
        # Identifiers are generated by the server; the check is a second line of defence.
        CheckConstraint("schema_name ~ '^ds_[0-9a-f]{32}$'", name="schema_name"),
        CheckConstraint("reader_role ~ '^ds_[0-9a-f]{32}_r$'", name="reader_role"),
        Index("ix_datasets_owner_id_created_at", "owner_id", text("created_at DESC")),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    owner_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    connection_id: Mapped[uuid.UUID] = mapped_column(
        # Checked at commit (deferred): a connection in use still can't be deleted, but
        # deleting the owning user can cascade through connections and datasets together.
        ForeignKey(
            "database_connections.id",
            ondelete="NO ACTION",
            deferrable=True,
            initially="DEFERRED",
        ),
        index=True,
        nullable=False,
    )
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    description: Mapped[str | None] = mapped_column(Text)
    source_type: Mapped[str] = mapped_column(String(16), nullable=False)
    file_name: Mapped[str | None] = mapped_column(String(255))
    schema_name: Mapped[str] = mapped_column(String(40), unique=True, nullable=False)
    reader_role: Mapped[str] = mapped_column(String(40), unique=True, nullable=False)
    status: Mapped[str] = mapped_column(String(16), nullable=False)
    status_reason: Mapped[str | None] = mapped_column(Text)
    version: Mapped[int] = mapped_column(Integer, nullable=False, default=1, server_default="1")
    total_rows: Mapped[int | None] = mapped_column(BigInteger)
    size_bytes: Mapped[int | None] = mapped_column(BigInteger)

    tables: Mapped[list[DatasetTable]] = relationship(
        back_populates="dataset", cascade="all, delete-orphan", order_by="DatasetTable.table_name"
    )
    relationships: Mapped[list[DatasetRelationship]] = relationship(
        back_populates="dataset", cascade="all, delete-orphan"
    )
    jobs: Mapped[list[IngestionJob]] = relationship(
        back_populates="dataset", cascade="all, delete-orphan"
    )


class DatasetTable(Base):
    __tablename__ = "dataset_tables"
    __table_args__ = (UniqueConstraint("dataset_id", "table_name"),)

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    dataset_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    table_name: Mapped[str] = mapped_column(String(63), nullable=False)
    display_name: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str | None] = mapped_column(Text)
    row_count: Mapped[int] = mapped_column(BigInteger, nullable=False, default=0)
    primary_key: Mapped[list[str]] = mapped_column(JSONB, nullable=False, default=list)

    dataset: Mapped[Dataset] = relationship(back_populates="tables")
    columns: Mapped[list[DatasetColumn]] = relationship(
        back_populates="table", cascade="all, delete-orphan", order_by="DatasetColumn.ordinal"
    )


class DatasetColumn(Base):
    __tablename__ = "dataset_columns"
    __table_args__ = (
        UniqueConstraint("table_id", "column_name"),
        CheckConstraint(_in("data_type", COLUMN_TYPES), name="data_type"),
        CheckConstraint(
            f"semantic_role IS NULL OR {_in('semantic_role', SEMANTIC_ROLES)}", name="semantic_role"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    table_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("dataset_tables.id", ondelete="CASCADE"), index=True, nullable=False
    )
    column_name: Mapped[str] = mapped_column(String(63), nullable=False)
    display_name: Mapped[str] = mapped_column(String(255), nullable=False)
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    data_type: Mapped[str] = mapped_column(String(16), nullable=False)
    inferred_type: Mapped[str | None] = mapped_column(String(16))
    is_nullable: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    is_primary_key: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    semantic_role: Mapped[str | None] = mapped_column(String(16))
    description: Mapped[str | None] = mapped_column(Text)
    # Sensitive columns never expose sample values (to the model or the preview API).
    is_sensitive: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default="false"
    )
    profile: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, default=dict)

    table: Mapped[DatasetTable] = relationship(back_populates="columns")


class DatasetRelationship(Base):
    """A join path between two tables: declared (real FK) or inferred."""

    __tablename__ = "dataset_relationships"
    __table_args__ = (
        CheckConstraint("origin IN ('declared', 'inferred')", name="origin"),
        UniqueConstraint("dataset_id", "from_table_id", "from_column", "to_table_id", "to_column"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    dataset_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    from_table_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("dataset_tables.id", ondelete="CASCADE"), index=True, nullable=False
    )
    from_column: Mapped[str] = mapped_column(String(63), nullable=False)
    to_table_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("dataset_tables.id", ondelete="CASCADE"), index=True, nullable=False
    )
    to_column: Mapped[str] = mapped_column(String(63), nullable=False)
    origin: Mapped[str] = mapped_column(String(16), nullable=False)
    constraint_name: Mapped[str | None] = mapped_column(String(63))

    dataset: Mapped[Dataset] = relationship(back_populates="relationships")
    from_table: Mapped[DatasetTable] = relationship(foreign_keys=[from_table_id])
    to_table: Mapped[DatasetTable] = relationship(foreign_keys=[to_table_id])


class IngestionJob(CreatedAtMixin, Base):
    __tablename__ = "ingestion_jobs"
    __table_args__ = (
        CheckConstraint("status IN ('pending', 'running', 'succeeded', 'failed')", name="status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    dataset_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    status: Mapped[str] = mapped_column(String(16), nullable=False)
    file_name: Mapped[str | None] = mapped_column(String(255))
    file_size: Mapped[int | None] = mapped_column(BigInteger)
    # Opaque id of the stored upload file (random; never the client's filename).
    upload_token: Mapped[str | None] = mapped_column(String(64), unique=True)
    rows_total: Mapped[int | None] = mapped_column(BigInteger)
    rows_loaded: Mapped[int | None] = mapped_column(BigInteger)
    rows_rejected: Mapped[int | None] = mapped_column(BigInteger)
    issues: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, nullable=False, default=list)
    inferred_schema: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB, nullable=False, default=list
    )
    error: Mapped[str | None] = mapped_column(Text)
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    dataset: Mapped[Dataset] = relationship(back_populates="jobs")
